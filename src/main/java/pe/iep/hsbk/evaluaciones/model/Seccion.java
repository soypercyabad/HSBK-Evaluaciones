package pe.iep.hsbk.evaluaciones.model;

public class Seccion {
  private String id;
  private String nombre;

  public Seccion() {
  }

  public String getId() {
    return id;
  }

  public void setId(String id) {
    this.id = id;
  }

  public String getNombre() {
    return nombre;
  }

  public void setNombre(String nombre) {
    this.nombre = nombre;
  }
}
